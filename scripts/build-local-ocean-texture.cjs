'use strict';
// Keep file:// previews self-contained without changing the WebP pixels or
// weakening browser security. HTTP/PWA previews continue using the image file.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const image=fs.readFileSync(path.join(root,'assets/ocean-surface-v1.webp'));
const source='/* Generated by node scripts/build-local-ocean-texture.cjs; do not edit. */\n'+
  'globalThis.OceanSurfaceLocalTexture='+JSON.stringify('data:image/webp;base64,'+image.toString('base64'))+';\n';
fs.writeFileSync(path.join(root,'assets/ocean-surface-v1.local.js'),source);
console.log('Built local ocean texture from '+image.length+' original WebP bytes.');
